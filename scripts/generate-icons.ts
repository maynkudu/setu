import { buildSvg } from "runeicons";
import { writeFile } from "node:fs/promises";
const names = {
  home: "tools-house",
  calendar: "schedule-calendar",
  message: "messaging-message-square-text",
  users: "identity-users",
  user: "identity-user-cog",
  bell: "messaging-mail",
  search: "tools-search",
  file: "documents-file-text",
  book: "documents-book-bookmark",
  shield: "identity-shield-check",
  check: "indicators-check",
  x: "indicators-x",
  chart: "metrics-chart-bar",
  target: "metrics-activity",
  menu: "layouts-menu",
};
const icons = Object.fromEntries(
  Object.entries(names).map(([key, name]) => {
    const svg = buildSvg(name, "normal", { size: 18 });
    if (!svg) throw new Error(`Missing icon ${name}`);
    return [key, svg];
  }),
);
await writeFile(
  "src/components/rune-data.ts",
  `// Generated by scripts/generate-icons.ts from Rune Icons, Apache-2.0.\nexport const rune = ${JSON.stringify(icons, null, 2)};\n`,
);
